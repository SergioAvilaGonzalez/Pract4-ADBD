-- El importe de un pedido no se guarda en pedidos porque se deriva de sus líneas.
-- La vista incluye pedidos sin líneas, asignándoles total 0.
CREATE VIEW vista_pedidos_totales AS
SELECT p.id AS id_pedido,
       p.fecha,
       p.id_empleado,
       p.id_cliente,
       COALESCE(SUM(pc.cantidad * pc.precio_unitario), 0::numeric)::numeric(12,2)
           AS importe_total
  FROM pedidos AS p
  LEFT JOIN pedidos_contenido AS pc ON pc.id_pedido = p.id
 GROUP BY p.id, p.fecha, p.id_empleado, p.id_cliente;

-- Volumen mensual de compras que se realizaron dentro del periodo de afiliación.
-- La política concreta que transforma ese volumen en un porcentaje de descuento
-- no se puede inferir sin los tramos/reglas de negocio de Tajinaste Plus.
CREATE VIEW vista_compras_mensuales_plus AS
SELECT p.id_cliente,
       date_trunc('month', p.fecha)::date AS mes,
       SUM(pc.cantidad * pc.precio_unitario)::numeric(12,2) AS volumen_compras
  FROM pedidos AS p
  JOIN tajinaste_plus AS tp ON tp.id_cliente = p.id_cliente
  JOIN pedidos_contenido AS pc ON pc.id_pedido = p.id
 WHERE p.fecha >= tp.inicio
   AND (tp.fin IS NULL OR p.fecha < tp.fin)
 GROUP BY p.id_cliente, date_trunc('month', p.fecha)::date;

