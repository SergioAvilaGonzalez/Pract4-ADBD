CREATE INDEX ix_tareas_id_zona ON tareas(id_zona);
CREATE INDEX ix_stock_codigo_producto ON stock(codigo_producto);
CREATE INDEX ix_pedidos_id_empleado ON pedidos(id_empleado);
CREATE INDEX ix_pedidos_id_cliente ON pedidos(id_cliente);
CREATE INDEX ix_contenido_id_producto ON pedidos_contenido(id_producto);
CREATE INDEX ix_bonificaciones_id_producto ON bonificaciones(id_producto);

-- ============================================================
-- VALIDACIÓN DE TAREAS
-- ============================================================

-- Comprueba la coherencia de una tarea con su asignación. Se separa en una
-- función reutilizable para validar tanto INSERT/UPDATE de tareas como UPDATE
-- de los datos padre que podrían invalidar tareas ya existentes.
CREATE OR REPLACE FUNCTION comprobar_coherencia_tarea(
    p_id_asignacion integer,
    p_id_zona integer,
    p_inicio timestamp,
    p_fin timestamp
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    vivero_puesto integer;
    vivero_zona   integer;
    inicio_asig   timestamp;
    fin_asig      timestamp;
BEGIN
    SELECT p.id_vivero, a.inicio, a.fin
      INTO vivero_puesto, inicio_asig, fin_asig
      FROM asignaciones AS a
      JOIN puestos AS p ON p.id = a.id_puesto
     WHERE a.id = p_id_asignacion;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No existe la asignación %', p_id_asignacion;
    END IF;

    SELECT z.id_vivero
      INTO vivero_zona
      FROM zonas AS z
     WHERE z.id = p_id_zona;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No existe la zona %', p_id_zona;
    END IF;

    IF vivero_puesto <> vivero_zona THEN
        RAISE EXCEPTION
            'La zona % y el puesto de la asignación % pertenecen a viveros distintos',
            p_id_zona, p_id_asignacion;
    END IF;

    IF NOT (tsrange(p_inicio, p_fin, '[)') <@ tsrange(inicio_asig, fin_asig, '[)')) THEN
        RAISE EXCEPTION
            'El periodo de la tarea debe estar contenido en el de la asignación %',
            p_id_asignacion;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION validar_tarea_asignacion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM comprobar_coherencia_tarea(
        NEW.id_asignacion, NEW.id_zona, NEW.inicio, NEW.fin
    );
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_tareas_validar_asignacion
BEFORE INSERT OR UPDATE ON tareas
FOR EACH ROW EXECUTE FUNCTION validar_tarea_asignacion();

-- Si se cambia una asignación, se comprueba que sus tareas sigan dentro del
-- intervalo asignado y en una zona del vivero correspondiente.
CREATE OR REPLACE FUNCTION validar_tareas_despues_cambio_asignacion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT id_asignacion, id_zona, inicio, fin
          FROM tareas
         WHERE id_asignacion = NEW.id
    LOOP
        PERFORM comprobar_coherencia_tarea(
            r.id_asignacion, r.id_zona, r.inicio, r.fin
        );
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tr_asignaciones_validar_tareas
AFTER UPDATE OF id_puesto, inicio, fin ON asignaciones
FOR EACH ROW EXECUTE FUNCTION validar_tareas_despues_cambio_asignacion();

-- Cambiar el vivero de un puesto no puede dejar tareas asociadas a zonas de
-- otro vivero.
CREATE OR REPLACE FUNCTION validar_tareas_despues_cambio_puesto()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT t.id_asignacion, t.id_zona, t.inicio, t.fin
          FROM tareas AS t
          JOIN asignaciones AS a ON a.id = t.id_asignacion
         WHERE a.id_puesto = NEW.id
    LOOP
        PERFORM comprobar_coherencia_tarea(
            r.id_asignacion, r.id_zona, r.inicio, r.fin
        );
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tr_puestos_validar_tareas
AFTER UPDATE OF id_vivero ON puestos
FOR EACH ROW EXECUTE FUNCTION validar_tareas_despues_cambio_puesto();

-- Cambiar el vivero de una zona tampoco puede invalidar las tareas históricas.
CREATE OR REPLACE FUNCTION validar_tareas_despues_cambio_zona()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT id_asignacion, id_zona, inicio, fin
          FROM tareas
         WHERE id_zona = NEW.id
    LOOP
        PERFORM comprobar_coherencia_tarea(
            r.id_asignacion, r.id_zona, r.inicio, r.fin
        );
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tr_zonas_validar_tareas
AFTER UPDATE OF id_vivero ON zonas
FOR EACH ROW EXECUTE FUNCTION validar_tareas_despues_cambio_zona();

