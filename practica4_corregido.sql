-- Practica 4 - Modelo relacional de Tajinaste S.A.
-- Gestor: PostgreSQL. Ejecutar con psql desde una base de datos distinta de viveros.
-- La orden \connect es una metaorden de psql (no SQL estándar).
-- Si la base de datos ya existe, omitir CREATE DATABASE y ejecutar \connect viveros.

CREATE DATABASE viveros;
\connect viveros

-- Necesaria para la restricción EXCLUDE que impide solapamientos temporales
-- de asignaciones de un mismo empleado. Puede requerir permisos de administrador.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE viveros (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    longitud    numeric(9,6) NOT NULL,
    latitud     numeric(8,6) NOT NULL,
    CONSTRAINT ck_viveros_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_viveros_latitud  CHECK (latitud BETWEEN -90 AND 90)
);

CREATE TABLE zonas (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vivero   integer NOT NULL,
    nombre      varchar(50) NOT NULL,
    longitud    numeric(9,6) NOT NULL,
    latitud     numeric(8,6) NOT NULL,
    CONSTRAINT uq_zonas_vivero_nombre UNIQUE (id_vivero, nombre),
    CONSTRAINT ck_zonas_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_zonas_latitud  CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT fk_zonas_viveros FOREIGN KEY (id_vivero)
        REFERENCES viveros(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE empleados (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni         varchar(9) NOT NULL UNIQUE,
    nombre      varchar(50) NOT NULL,
    apellido    varchar(50) NOT NULL,
    nacimiento  date NOT NULL,
    CONSTRAINT ck_empleados_dni_formato CHECK (dni ~ '^[0-9]{8}[A-Z]$'),
    CONSTRAINT ck_empleados_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_empleados_apellido CHECK (btrim(apellido) <> ''),
    CONSTRAINT ck_empleados_nacimiento CHECK (nacimiento < CURRENT_DATE)
);

CREATE TABLE puestos (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vivero   integer NOT NULL,
    nombre      varchar(50) NOT NULL,
    descripcion varchar(1024) NOT NULL,
    CONSTRAINT ck_puestos_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT fk_puestos_viveros FOREIGN KEY (id_vivero)
        REFERENCES viveros(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE asignaciones (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_puesto    integer NOT NULL,
    id_empleado  integer NOT NULL,
    inicio       timestamp NOT NULL,
    fin          timestamp,
    CONSTRAINT ck_asignaciones_periodo CHECK (fin IS NULL OR fin > inicio),
    CONSTRAINT fk_asignaciones_puestos FOREIGN KEY (id_puesto)
        REFERENCES puestos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_asignaciones_empleados FOREIGN KEY (id_empleado)
        REFERENCES empleados(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    -- Los intervalos son [inicio, fin): dos asignaciones consecutivas pueden
    -- tocarse en el límite, pero no pueden solaparse para el mismo empleado.
    CONSTRAINT ex_asignaciones_sin_solapamiento
        EXCLUDE USING gist (
            id_empleado WITH =,
            tsrange(inicio, fin, '[)') WITH &&
        )
);

-- Una tarea se vincula a una asignación concreta para poder validar que
-- la zona pertenece al vivero del puesto y que sus fechas caben en la asignación.
CREATE TABLE tareas (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asignacion   integer NOT NULL,
    id_zona         integer NOT NULL,
    inicio          timestamp NOT NULL,
    fin             timestamp,
    CONSTRAINT ck_tareas_periodo CHECK (fin IS NULL OR fin > inicio),
    CONSTRAINT fk_tareas_asignaciones FOREIGN KEY (id_asignacion)
        REFERENCES asignaciones(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_tareas_zonas FOREIGN KEY (id_zona)
        REFERENCES zonas(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE productos (
    codigo_de_barras varchar(20) PRIMARY KEY,
    precio           numeric(10,2) NOT NULL,
    nombre           varchar(50) NOT NULL,
    CONSTRAINT ck_productos_precio CHECK (precio >= 0),
    CONSTRAINT ck_productos_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE stock (
    id_zona         integer NOT NULL,
    codigo_producto varchar(20) NOT NULL,
    cantidad        integer NOT NULL,
    CONSTRAINT pk_stock PRIMARY KEY (id_zona, codigo_producto),
    CONSTRAINT ck_stock_cantidad CHECK (cantidad >= 0),
    CONSTRAINT fk_stock_zonas FOREIGN KEY (id_zona)
        REFERENCES zonas(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_stock_productos FOREIGN KEY (codigo_producto)
        REFERENCES productos(codigo_de_barras) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE clientes (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   varchar(50) NOT NULL,
    apellido varchar(50),
    CONSTRAINT ck_clientes_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_clientes_apellido CHECK (apellido IS NULL OR btrim(apellido) <> '')
);

CREATE TABLE clientes_correos (
    id_cliente integer NOT NULL,
    correo     varchar(255) NOT NULL,
    CONSTRAINT pk_clientes_correos PRIMARY KEY (id_cliente, correo),
    CONSTRAINT ck_clientes_correos_formato CHECK (correo ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    CONSTRAINT fk_correos_clientes FOREIGN KEY (id_cliente)
        REFERENCES clientes(id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Se asume un único periodo de pertenencia por cliente. Si un cliente pudiera
-- darse de baja y volver a inscribirse, esta tabla necesitaría una clave propia.
CREATE TABLE tajinaste_plus (
    id_cliente integer PRIMARY KEY,
    inicio     timestamp NOT NULL,
    fin        timestamp,
    CONSTRAINT ck_tajinaste_plus_periodo CHECK (fin IS NULL OR fin > inicio),
    CONSTRAINT fk_tajinaste_plus_clientes FOREIGN KEY (id_cliente)
        REFERENCES clientes(id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE pedidos (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_empleado integer NOT NULL,
    id_cliente  integer NOT NULL,
    CONSTRAINT fk_pedidos_empleados FOREIGN KEY (id_empleado)
        REFERENCES empleados(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pedidos_clientes FOREIGN KEY (id_cliente)
        REFERENCES clientes(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE pedidos_contenido (
    id_pedido       integer NOT NULL,
    id_producto     varchar(20) NOT NULL,
    cantidad        integer NOT NULL,
    precio_unitario numeric(10,2) NOT NULL,
    CONSTRAINT pk_pedidos_contenido PRIMARY KEY (id_pedido, id_producto),
    CONSTRAINT ck_pedidos_contenido_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_pedidos_contenido_precio CHECK (precio_unitario >= 0),
    CONSTRAINT fk_contenido_pedidos FOREIGN KEY (id_pedido)
        REFERENCES pedidos(id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Se preserva el catálogo histórico: un producto vendido no puede borrarse.
    CONSTRAINT fk_contenido_productos FOREIGN KEY (id_producto)
        REFERENCES productos(codigo_de_barras) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE bonificaciones (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente     integer NOT NULL,
    id_producto    varchar(20) NOT NULL,
    mes_referencia date NOT NULL,
    descuento      numeric(5,2) NOT NULL,
    valido_desde   timestamp NOT NULL,
    valido_hasta   timestamp NOT NULL,
    CONSTRAINT uq_bonificaciones_cliente_producto_mes
        UNIQUE (id_cliente, id_producto, mes_referencia),
    CONSTRAINT ck_bonificaciones_mes CHECK (
        mes_referencia = date_trunc('month', mes_referencia)::date
    ),
    CONSTRAINT ck_bonificaciones_descuento CHECK (descuento BETWEEN 0 AND 100),
    CONSTRAINT ck_bonificaciones_vigencia CHECK (valido_hasta > valido_desde),
    CONSTRAINT fk_bonificaciones_tajinaste_plus FOREIGN KEY (id_cliente)
        REFERENCES tajinaste_plus(id_cliente) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_bonificaciones_productos FOREIGN KEY (id_producto)
        REFERENCES productos(codigo_de_barras) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Índices auxiliares para las columnas usadas como claves foráneas.
CREATE INDEX ix_puestos_id_vivero ON puestos(id_vivero);
